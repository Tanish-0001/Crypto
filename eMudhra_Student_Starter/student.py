def inverse_mod(a, modulus):
    """Return a^-1 modulo modulus; raise ValueError if there is no inverse.

    Iterative extended Euclidean algorithm. Invariant at every step:
        old_s * a  ≡ old_r  (mod modulus)
            s * a  ≡     r  (mod modulus)
    When the remainder sequence ends, old_r = gcd(a, modulus). If that gcd
    is 1 then old_s * a ≡ 1, so old_s is an inverse
    """
    if modulus < 2:
        raise ValueError("modulus must be at least 2")

    # old_r = r * q + new_r

    old_r, r = a % modulus, modulus
    old_s, s = 1, 0
    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s

    if old_r != 1:
        raise ValueError(f"{a} has no inverse modulo {modulus} (gcd = {old_r})")
    return old_s % modulus


def is_on_curve(point, curve=P384):
    """True for None or a canonical affine point on this curve."""
    if point is None:
        return True
        
    x, y = point
    if not (0 <= x < curve.p) or not (0 <= y < curve.p):
        return False

    return (y * y - (x * x * x + curve.a * x + curve.b)) % curve.p == 0


def _cofactor_is_one(curve):
    """True when every point on the curve lies in the subgroup generated by g.

    Hasse: the group order N satisfies N <= p + 1 + 2*sqrt(p). Since n divides
    N, a cofactor h = N/n >= 2 would force N >= 2n. So if 2n exceeds the Hasse
    upper bound then h = 1 and N = n. Checked in integers as
        2n - p - 1 > 0  and  (2n - p - 1)^2 > 4p.
    Holds for P-384 (h = 1) and TOY; fails for ORDER_TWO.
    """
    gap = 2 * curve.n - curve.p - 1
    return gap > 0 and gap * gap > 4 * curve.p


def is_valid_public_key(point, curve=P384):
    """Full public-key validation (SEC 1 v2 section 3.2.2.1 / SP 800-186):

    1. finite: not the identity (a key equal to O would be d ≡ 0 mod n),
    2. canonical coordinates on the curve (is_on_curve),
    3. in the order-n subgroup: n*Q = O.

    Step 3 is skipped for cofactor-1 curves such as P-384, where step 2
    already implies it; otherwise it is computed explicitly with scalar_mul.
    n*Q = O says ord(Q) divides n; that equals membership in <g> whenever
    n^2 does not divide the group order (true for every standard curve).
    """
    if point is None or not is_on_curve(point, curve):
        return False
    if _cofactor_is_one(curve):
        return True
    return scalar_mul(curve.n, point, curve) is None


def point_add(left, right, curve=P384):
    """Add valid points; handle infinity, opposites and y=0 doubling.

    Affine chord-and-tangent law over F_p (None is the identity O):
      P + O = O + P = P
      x1 == x2 and y1 + y2 ≡ 0   ->  O   (P + (-P); also covers doubling y=0,
                                         where the tangent is vertical)
      P == Q                     ->  lambda = (3*x1^2 + a) / (2*y1)
      x1 != x2                   ->  lambda = (y2 - y1) / (x2 - x1)
      x3 = lambda^2 - x1 - x2,  y3 = lambda*(x1 - x3) - y1   (all mod p)
    Division is multiplication by inverse_mod(., p); the special cases above
    guarantee the denominator is nonzero mod p, so the inverse always exists.
    """
    for point in (left, right):
        if not is_on_curve(point, curve):
            raise ValueError(f"point {point!r} is not a valid point on the curve")

    if left is None:
        return right
    if right is None:
        return left

    p = curve.p
    x1, y1 = left
    x2, y2 = right

    if x1 == x2:
        # Same x on a valid curve means y2 = ±y1.
        if (y1 + y2) % p == 0:
            return None  # opposite points, or doubling a point with y = 0
        # Otherwise y1 == y2 != 0: tangent-line doubling.
        lam = (3 * x1 * x1 + curve.a) * inverse_mod(2 * y1, p) % p
    else:
        lam = (y2 - y1) * inverse_mod(x2 - x1, p) % p

    x3 = (lam * lam - x1 - x2) % p
    y3 = (lam * (x1 - x3) - y1) % p
    return (x3, y3)


def scalar_mul(k, point, curve=P384):
    """Double and add for nonnegative k. Do not reduce k modulo curve.n.

    Left-to-right binary method: scan k's bits from the most significant;
    for each bit double the accumulator, and add `point` when the bit is 1.
    Invariant: after processing the top i bits, R = (those bits as an int)*P.
    k = 0 returns None (the identity), as does P = None for any k.

    k is deliberately NOT reduced mod curve.n. is_valid_public_key decides
    subgroup membership by testing n*Q == O; if k were reduced first, n*Q
    would become 0*Q = O for every Q and the check would always pass.
    """
    if not isinstance(k, int) or isinstance(k, bool):
        raise TypeError("scalar must be an integer")
    if k < 0:
        raise ValueError("scalar must be nonnegative")
    if not is_on_curve(point, curve):
        raise ValueError(f"point {point!r} is not a valid point on the curve")

    result = None
    for bit in bin(k)[2:]:          # bin(0) == '0b0' -> one zero bit -> None
        result = point_add(result, result, curve)
        if bit == "1":
            result = point_add(result, point, curve)
    return result


def recover_small_scalar(public_point, bound=256, curve=P384):
    """Search 1 <= d < bound using successive additions; return d or None.
    Raise ValueError for an invalid/infinite public point or bound < 2.

    Walk G, 2G, 3G, ... by adding G each step (one point addition per
    candidate, instead of a fresh scalar multiplication), and compare each
    multiple with the public point.
    """
    if bound < 2:
        raise ValueError("bound must be at least 2")
    if not is_valid_public_key(public_point, curve):
        raise ValueError("public point is not a valid public key")

    current = None                      # 0*G
    for d in range(1, bound):           # exactly 1 <= d < bound
        current = point_add(current, curve.g, curve)   # now current = d*G
        if current == public_point:
            # Substantiate the hit independently of the walk.
            if scalar_mul(d, curve.g, curve) != public_point:
                raise RuntimeError(f"recomputed {d}*G does not match the public point")
            return d
    return None


def recover_from_candidates(public_point, candidates, curve=P384):
    """Search the supplied finite candidate set; return matching d or None.
    Reject candidate scalars outside 1 <= d < n and invalid public points.
    """
    if not is_valid_public_key(public_point, curve):
        raise ValueError("public point is not a valid public key")
    candidates = list(candidates)
    for d in candidates:                # check the whole set before searching
        if not 1 <= d < curve.n:
            raise ValueError(f"candidate {d} is outside 1 <= d < n")

    for d in candidates:
        if scalar_mul(d, curve.g, curve) == public_point:
            return d
    return None


def _hash_to_int(message):
    """z = int(SHA-384(M)). SHA-384 output is 384 bits, the same length as n,
    so no truncation of the hash is needed for P-384."""
    return int.from_bytes(hashlib.sha384(message).digest(), "big")


def sign_message(d, message):
    """Return (r,s), ECDSA P-384/SHA-384 with a fresh CSPRNG nonce."""
    n, G = P384.n, P384.g
    if not 1 <= d < n:
        raise ValueError("private scalar must satisfy 1 <= d < n")
    z = _hash_to_int(message)

    while True:
        k = secrets.randbelow(n - 1) + 1        # fresh nonce, 1 <= k < n
        R = scalar_mul(k, G)
        r = R[0] % n
        if r == 0:
            continue                            # retry with a new nonce
        s = inverse_mod(k, n) * (z + r * d) % n
        if s == 0:
            continue                            # retry with a new nonce
        return (r, s)


def verify_message(public_point, message, signature):
    """Boolean ECDSA P-384/SHA-384 verification; reject invalid points/r/s."""
    n, G = P384.n, P384.g
    if not is_valid_public_key(public_point):
        return False                            # invalid or infinite Q
    r, s = signature
    if not (1 <= r < n and 1 <= s < n):
        return False

    z = _hash_to_int(message)
    w = inverse_mod(s, n)
    u1 = z * w % n
    u2 = r * w % n
    U = point_add(scalar_mul(u1, G), scalar_mul(u2, public_point))
    if U is None:
        return False
    return U[0] % n == r


def forge_lab_certificate(d, issuer):
    """Return a certificate for grades.crypto.test signed by recovered d.
    Generate a fresh leaf key; use leaf_template and the cryptography package.
    Reject d unless its public key matches issuer.public_key().
    """
    # 1. Rebuild the intermediate's signing key and prove it is the right one.
    ca_key = ec.derive_private_key(d, ec.SECP384R1())
    if point_of(ca_key.public_key()) != point_of(issuer.public_key()):
        raise ValueError("d does not match the issuer's public key")

    # 2. Fresh key pair for the leaf (never reuse the CA key for the leaf).
    leaf_key = ec.generate_private_key(ec.SECP384R1())

    # 3. Fill the supplied template and sign it with the CA key.
    cert = leaf_template(issuer, leaf_key.public_key()).sign(ca_key, hashes.SHA384())

    # 4. Check the signature under the issuer certificate's public key
    #    (raises InvalidSignature if it does not verify).
    issuer.public_key().verify(cert.signature, cert.tbs_certificate_bytes,
                               ec.ECDSA(hashes.SHA384()))
    return cert


def validate_chain(chain, trust_anchors, *, blocked_spki=(), revoked=(),
                   at=CHECK_TIME, hostname=HOSTNAME):
    """Return (accepted: bool, diagnostic: str) for the stated three-cert profile.
    chain = [leaf, intermediate, root]. Anchors are certificate SHA-256 hex.
    blocked_spki holds SHA-256 hex of DER SPKI.
    revoked holds (issuer SPKI SHA-256 hex, certificate serial) pairs.
    No network, path discovery, OCSP or system trust-store access is required.
    """
    try:
        _check_chain(chain, trust_anchors, blocked_spki, revoked, at, hostname)
    except _Reject as exc:
        return False, str(exc)
    except (ValueError, InvalidSignature) as exc:      # fail closed on malformed input
        return False, f"malformed certificate: {exc}"
    return True, "accepted"


class _Reject(Exception):
    """Raised by the chain checks with a human-readable reason."""


# The only extensions this profile supports; any other one rejects.
_SUPPORTED_EXTENSIONS = {
    ExtensionOID.BASIC_CONSTRAINTS, ExtensionOID.KEY_USAGE,
    ExtensionOID.EXTENDED_KEY_USAGE, ExtensionOID.SUBJECT_ALTERNATIVE_NAME,
}


def _ext(cert, ext_class, label):
    """Return the extension (with .value and .critical), or reject if missing."""
    try:
        return cert.extensions.get_extension_for_class(ext_class)
    except x509.ExtensionNotFound:
        raise _Reject(f"{label}: missing {ext_class.__name__}")


def _optional_ext(cert, ext_class):
    try:
        return cert.extensions.get_extension_for_class(ext_class).value
    except x509.ExtensionNotFound:
        return None


def _check_chain(chain, trust_anchors, blocked_spki, revoked, at, hostname):
    # 1. Shape: exactly three v3 certificates, P-384 keys, ECDSA/SHA-384.
    if not isinstance(chain, (list, tuple)) or len(chain) != 3:
        raise _Reject("path must be exactly [leaf, intermediate, root]")
    if not all(isinstance(c, x509.Certificate) for c in chain):
        raise _Reject("path contains a non-certificate")
    leaf, inter, root = chain
    named = list(zip(["leaf", "intermediate", "root"], chain))
    for label, cert in named:
        if cert.version != x509.Version.v3:
            raise _Reject(f"{label}: not X.509 v3")
        key = cert.public_key()
        if not isinstance(key, ec.EllipticCurvePublicKey) or key.curve.name != "secp384r1":
            raise _Reject(f"{label}: public key is not P-384")
        if cert.signature_algorithm_oid != SignatureAlgorithmOID.ECDSA_WITH_SHA384:
            raise _Reject(f"{label}: signature algorithm is not ECDSA/SHA-384")

    # 2. Trust anchor: the exact root certificate, never just its name.
    if certificate_sha256(root) not in trust_anchors:
        raise _Reject("root: certificate fingerprint is not a trust anchor")

    # 3. Validity at the supplied clock (applies to the root too in this lab).
    if at.tzinfo is None:
        raise _Reject("clock must be timezone-aware")
    for label, cert in named:
        if not cert.not_valid_before_utc <= at <= cert.not_valid_after_utc:
            raise _Reject(f"{label}: not valid at {at.isoformat()}")

    # 4. Issuer-name linkage and signatures, including the root self-signature.
    #    verify_directly_issued_by checks issuer == subject and the signature.
    for label, cert, issuer in [("leaf", leaf, inter), ("intermediate", inter, root),
                                ("root", root, root)]:
        try:
            cert.verify_directly_issued_by(issuer)
        except (ValueError, InvalidSignature) as exc:
            raise _Reject(f"{label}: issuer name or signature check failed ({type(exc).__name__})")

    # 5. Extensions: only the supported set, and BasicConstraints + KeyUsage everywhere.
    for label, cert in named:
        for ext in cert.extensions:
            if ext.oid not in _SUPPORTED_EXTENSIONS:
                raise _Reject(f"{label}: unsupported extension {ext.oid.dotted_string}")
        _ext(cert, x509.BasicConstraints, label)
        _ext(cert, x509.KeyUsage, label)

    # 6. CA certificates: critical CA=true, keyCertSign, path length, and any
    #    EKU must permit server auth. Path length counts the non-self-issued CA
    #    certificates below the issuer, excluding the leaf.
    below_root = 0 if inter.subject == inter.issuer else 1
    for label, cert, below in [("root", root, below_root), ("intermediate", inter, 0)]:
        bc = _ext(cert, x509.BasicConstraints, label)
        if not bc.critical or not bc.value.ca:
            raise _Reject(f"{label}: needs critical BasicConstraints with CA=true")
        if bc.value.path_length is not None and bc.value.path_length < below:
            raise _Reject(f"{label}: path length {bc.value.path_length} < {below} CA below it")
        if not _ext(cert, x509.KeyUsage, label).value.key_cert_sign:
            raise _Reject(f"{label}: KeyUsage lacks keyCertSign")
        eku = _optional_ext(cert, x509.ExtendedKeyUsage)
        if eku is not None and not ({ExtendedKeyUsageOID.SERVER_AUTH,
                                     ExtendedKeyUsageOID.ANY_EXTENDED_KEY_USAGE} & set(eku)):
            raise _Reject(f"{label}: ExtendedKeyUsage does not permit serverAuth")

    # 7. Leaf: not a CA, digitalSignature but not keyCertSign, serverAuth, and
    #    an exact SAN DNS match (no CN fallback, no wildcards; DNS ignores case).
    if _ext(leaf, x509.BasicConstraints, "leaf").value.ca:
        raise _Reject("leaf: BasicConstraints CA is true")
    ku = _ext(leaf, x509.KeyUsage, "leaf").value
    if not ku.digital_signature or ku.key_cert_sign:
        raise _Reject("leaf: KeyUsage must have digitalSignature and not keyCertSign")
    if ExtendedKeyUsageOID.SERVER_AUTH not in _ext(leaf, x509.ExtendedKeyUsage, "leaf").value:
        raise _Reject("leaf: ExtendedKeyUsage lacks serverAuth")
    names = _ext(leaf, x509.SubjectAlternativeName, "leaf").value.get_values_for_type(x509.DNSName)
    if hostname.lower() not in [n.lower() for n in names]:
        raise _Reject(f"leaf: {hostname} not in SAN DNS names {names}")

    # 8. Local policy: blocked keys (any position) and revoked certificates.
    #    Revocation is keyed by (issuer key, serial), so it names one certificate.
    for label, cert in named:
        if spki_sha256(cert) in blocked_spki:
            raise _Reject(f"{label}: public key (SPKI) is blocked")
    for label, cert, issuer in [("leaf", leaf, inter), ("intermediate", inter, root)]:
        if (spki_sha256(issuer), cert.serial_number) in revoked:
            raise _Reject(f"{label}: serial {cert.serial_number} revoked by its issuer")


def ceremony_consistent(expected_spki_pem, csr_pem, cert_pem):
    """Verify CSR signature and match all three DER SPKI encodings. Return bool."""
    try:
        expected = serialization.load_pem_public_key(expected_spki_pem)
        csr = x509.load_pem_x509_csr(csr_pem)
        cert = x509.load_pem_x509_certificate(cert_pem)
        if not csr.is_signature_valid:      # proves possession of the CSR's key only
            return False
        return spki_bytes(expected) == spki_bytes(csr.public_key()) == spki_bytes(cert.public_key())
    except (ValueError, TypeError):         # malformed input: reject
        return False


